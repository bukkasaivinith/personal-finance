  Personal finance: secure workspaces, transaction editing, recurring automation,
  and auditable history.

  This migration intentionally keeps every existing row. Legacy rows start with a
  NULL owner and are claimed exactly once by the first signed-in workspace owner
  through claim_unowned_finance_data(). Until claimed, RLS exposes them to nobody.
*/

