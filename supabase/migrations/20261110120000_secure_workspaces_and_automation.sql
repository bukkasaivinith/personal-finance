-- A single user may safely claim the original unowned single-user workspace.
CREATE OR REPLACE FUNCTION public.claim_unowned_finance_data()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller uuid := auth.uid();
  owned_elsewhere boolean;
BEGIN
  IF caller IS NULL THEN RAISE EXCEPTION 'Sign in before opening a workspace.'; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('personal-finance-legacy-workspace'));
  SELECT EXISTS (
    SELECT 1 FROM public.transaction_types WHERE user_id IS NOT NULL AND user_id <> caller
    UNION ALL SELECT 1 FROM public.categories WHERE user_id IS NOT NULL AND user_id <> caller
    UNION ALL SELECT 1 FROM public.accounts WHERE user_id IS NOT NULL AND user_id <> caller
    UNION ALL SELECT 1 FROM public.transactions WHERE user_id IS NOT NULL AND user_id <> caller
  ) INTO owned_elsewhere;
  -- A new user gets an empty secure workspace rather than someone else's records.
  IF owned_elsewhere THEN RETURN; END IF;

  UPDATE public.transaction_types SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.categories SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.accounts SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.category_transaction_types SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.budgets SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.recurring_entries SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.transactions SET user_id = caller WHERE user_id IS NULL;
  UPDATE public.audit_events SET user_id = caller WHERE user_id IS NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.next_recurring_date(p_date date, p_interval integer, p_unit text, p_month_day smallint)
RETURNS date
LANGUAGE plpgsql
IMMUTABLE
SET search_path = public
AS $$
DECLARE
  target_month date;
  target_day integer;
BEGIN
  IF p_unit = 'day' THEN RETURN p_date + p_interval; END IF;
  IF p_unit = 'week' THEN RETURN p_date + (p_interval * 7); END IF;
  target_month := (date_trunc('month', p_date)::date + (p_interval || ' months')::interval)::date;
  target_day := LEAST(COALESCE(p_month_day, EXTRACT(DAY FROM p_date)::smallint),
                      EXTRACT(DAY FROM (date_trunc('month', target_month) + interval '1 month - 1 day'))::integer);
  RETURN make_date(EXTRACT(YEAR FROM target_month)::integer, EXTRACT(MONTH FROM target_month)::integer, target_day);
END;
$$;

CREATE OR REPLACE FUNCTION public.process_due_recurring_entries()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller uuid := auth.uid();
  rule public.recurring_entries%ROWTYPE;
  due_date date;
  generated integer := 0;
BEGIN
  IF caller IS NULL THEN RAISE EXCEPTION 'Sign in before processing recurring entries.'; END IF;
  FOR rule IN
    SELECT * FROM public.recurring_entries
    WHERE user_id = caller AND is_active AND next_date <= CURRENT_DATE
      AND (end_date IS NULL OR next_date <= end_date)
    ORDER BY next_date
    FOR UPDATE
  LOOP
    due_date := rule.next_date;
    WHILE due_date <= CURRENT_DATE AND (rule.end_date IS NULL OR due_date <= rule.end_date) LOOP
      INSERT INTO public.transactions (
        user_id, name, transaction_type_id, category_id, amount, transaction_date,
        transaction_time, account_id, to_account_id, recurring_entry_id, transaction_source
      ) VALUES (
        caller, rule.name, rule.transaction_type_id, rule.category_id, rule.amount, due_date,
        NULL, rule.account_id, rule.to_account_id, rule.id, 'scheduled'
      ) ON CONFLICT (recurring_entry_id, transaction_date) WHERE recurring_entry_id IS NOT NULL DO NOTHING;
      IF FOUND THEN generated := generated + 1; END IF;
      due_date := public.next_recurring_date(due_date, rule.interval_value, rule.interval_unit, rule.month_day);
    END LOOP;
    UPDATE public.recurring_entries
    SET next_date = due_date,
        is_active = CASE WHEN end_date IS NOT NULL AND due_date > end_date THEN false ELSE is_active END,
        updated_at = now()
    WHERE id = rule.id AND user_id = caller;
  END LOOP;
  RETURN generated;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_auth_activity(p_action text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  caller uuid := auth.uid();
  email_label text := COALESCE(auth.jwt() ->> 'email', 'Signed-in user');
BEGIN
  IF caller IS NULL OR p_action NOT IN ('signed_in', 'signed_out') THEN RETURN; END IF;
  INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
  VALUES (caller, 'authentication', caller, email_label, p_action);
END;
$$;

