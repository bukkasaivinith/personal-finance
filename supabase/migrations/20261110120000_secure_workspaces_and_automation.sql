-- Existing audit trigger now records the owner too, but ignores the one-time ownership claim itself.
CREATE OR REPLACE FUNCTION public.record_item_audit() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  change_action text;
  owner_id uuid;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
    VALUES (NEW.user_id, TG_TABLE_NAME, NEW.id, NEW.name, 'created');
    RETURN NEW;
  ELSIF TG_OP = 'DELETE' THEN
    INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
    VALUES (OLD.user_id, TG_TABLE_NAME, OLD.id, OLD.name, 'permanently_deleted');
    RETURN OLD;
  END IF;

  IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    RETURN NEW;
  END IF;
  IF NEW.deleted_at IS NOT NULL AND OLD.deleted_at IS NULL THEN
    change_action := 'deleted';
  ELSIF NEW.deleted_at IS NULL AND OLD.deleted_at IS NOT NULL THEN
    change_action := 'restored';
  ELSIF NEW.is_active IS DISTINCT FROM OLD.is_active THEN
    change_action := CASE WHEN NEW.is_active THEN 'activated' ELSE 'deactivated' END;
  ELSIF NEW.name IS DISTINCT FROM OLD.name THEN
    change_action := 'renamed';
  ELSE
    change_action := 'updated';
  END IF;
  owner_id := NEW.user_id;
  INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
  VALUES (owner_id, TG_TABLE_NAME, NEW.id, NEW.name, change_action);
  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_transaction_audit() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
    VALUES (NEW.user_id, 'transactions', NEW.id, NEW.name || ' — ' || NEW.amount::text, 'created');
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN RETURN NEW; END IF;
    -- Renaming a setup item refreshes saved display labels. That is derived
    -- data, not a user editing every historic transaction, so do not flood
    -- the activity feed with one event per refreshed label.
    IF NEW.name IS NOT DISTINCT FROM OLD.name
       AND NEW.transaction_type_id IS NOT DISTINCT FROM OLD.transaction_type_id
       AND NEW.category_id IS NOT DISTINCT FROM OLD.category_id
       AND NEW.amount IS NOT DISTINCT FROM OLD.amount
       AND NEW.transaction_date IS NOT DISTINCT FROM OLD.transaction_date
       AND NEW.transaction_time IS NOT DISTINCT FROM OLD.transaction_time
       AND NEW.account_id IS NOT DISTINCT FROM OLD.account_id
       AND NEW.to_account_id IS NOT DISTINCT FROM OLD.to_account_id
       AND NEW.recurring_entry_id IS NOT DISTINCT FROM OLD.recurring_entry_id
       AND NEW.transaction_source IS NOT DISTINCT FROM OLD.transaction_source THEN
      RETURN NEW;
    END IF;
    INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
    VALUES (NEW.user_id, 'transactions', NEW.id, NEW.name || ' — ' || NEW.amount::text, 'updated');
    RETURN NEW;
  END IF;
  INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
  VALUES (OLD.user_id, 'transactions', OLD.id, OLD.name || ' — ' || OLD.amount::text, 'deleted');
  RETURN OLD;
END;
$$;

CREATE OR REPLACE FUNCTION public.record_simple_audit() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  label text;
  change_action text;
  owner_id uuid;
  changed_id uuid;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    RETURN NEW;
  END IF;
  IF TG_OP = 'DELETE' THEN
    owner_id := OLD.user_id;
    changed_id := OLD.id;
  ELSE
    owner_id := NEW.user_id;
    changed_id := NEW.id;
  END IF;
  IF TG_TABLE_NAME = 'budgets' THEN
    label := CASE WHEN TG_OP = 'DELETE' THEN OLD.amount::text ELSE NEW.amount::text END || ' budget';
  ELSE
    label := CASE WHEN TG_OP = 'DELETE' THEN OLD.name ELSE NEW.name END;
  END IF;
  IF TG_OP = 'INSERT' THEN change_action := 'created';
  ELSIF TG_OP = 'DELETE' THEN change_action := 'deleted';
  ELSIF TG_TABLE_NAME = 'recurring_entries' AND NEW.is_active IS DISTINCT FROM OLD.is_active THEN
    change_action := CASE WHEN NEW.is_active THEN 'resumed' ELSE 'paused' END;
  ELSE change_action := 'updated';
  END IF;
  INSERT INTO public.audit_events (user_id, entity_table, entity_id, entity_name, action)
  VALUES (owner_id, TG_TABLE_NAME, changed_id, label, change_action);
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS transactions_audit ON public.transactions;
CREATE TRIGGER transactions_audit AFTER INSERT OR UPDATE OR DELETE ON public.transactions
FOR EACH ROW EXECUTE FUNCTION public.record_transaction_audit();
