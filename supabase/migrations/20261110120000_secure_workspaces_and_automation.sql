CREATE TRIGGER recurring_entries_audit AFTER INSERT OR UPDATE OR DELETE ON public.recurring_entries
FOR EACH ROW EXECUTE FUNCTION public.record_simple_audit();

-- Transaction validation now runs for edits as well as inserts and rejects cross-workspace references.
CREATE OR REPLACE FUNCTION public.snapshot_transaction_history()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  tt record;
  cat record;
  acc record;
BEGIN
  IF TG_OP = 'UPDATE' AND NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    -- claim_unowned_finance_data() is the only valid owner change. It must
    -- preserve historic rows even when an old type or category was archived.
    IF OLD.user_id IS NULL AND NEW.user_id = auth.uid() THEN RETURN NEW; END IF;
    RAISE EXCEPTION 'A transaction cannot be moved to another workspace.';
  END IF;

  SELECT name, kind INTO tt
  FROM public.transaction_types
  WHERE id = NEW.transaction_type_id
    AND user_id = NEW.user_id
    AND deleted_at IS NULL AND is_active;
  IF NOT FOUND THEN RAISE EXCEPTION 'That transaction type is no longer available.'; END IF;
  NEW.transaction_type_name := tt.name;
  NEW.transaction_kind := tt.kind;

  IF NEW.category_id IS NULL THEN
    IF tt.kind <> 'transfer' THEN RAISE EXCEPTION 'Choose a category that fits this transaction type.'; END IF;
    NEW.category_name := NULL;
  ELSE
    SELECT c.name INTO cat
    FROM public.categories c
    JOIN public.category_transaction_types l
      ON l.category_id = c.id AND l.transaction_type_id = NEW.transaction_type_id AND l.user_id = NEW.user_id
    WHERE c.id = NEW.category_id AND c.user_id = NEW.user_id AND c.deleted_at IS NULL AND c.is_active;
    IF NOT FOUND THEN RAISE EXCEPTION 'That category does not fit this transaction type.'; END IF;
    NEW.category_name := cat.name;
  END IF;

  SELECT name INTO acc FROM public.accounts
  WHERE id = NEW.account_id AND user_id = NEW.user_id AND deleted_at IS NULL AND is_active;
  IF NOT FOUND THEN RAISE EXCEPTION 'That account is no longer available.'; END IF;
  NEW.account_name := acc.name;

  IF tt.kind = 'transfer' THEN
    IF NEW.to_account_id IS NULL THEN RAISE EXCEPTION 'Choose the account to move money into.'; END IF;
    SELECT name INTO acc FROM public.accounts
    WHERE id = NEW.to_account_id AND user_id = NEW.user_id AND deleted_at IS NULL AND is_active;
    IF NOT FOUND THEN RAISE EXCEPTION 'That account is no longer available.'; END IF;
    NEW.to_account_name := acc.name;
  ELSE
    IF NEW.to_account_id IS NOT NULL THEN RAISE EXCEPTION 'Only transfers can have a destination account.'; END IF;
    NEW.to_account_name := NULL;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS snapshot_transaction_history ON public.transactions;
CREATE TRIGGER snapshot_transaction_history
  BEFORE INSERT OR UPDATE ON public.transactions
  FOR EACH ROW EXECUTE FUNCTION public.snapshot_transaction_history();

-- The category link is also kept inside the authenticated user's workspace.
CREATE OR REPLACE FUNCTION public.validate_category_transaction_type_link()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.categories WHERE id = NEW.category_id AND user_id = NEW.user_id)
     OR NOT EXISTS (SELECT 1 FROM public.transaction_types WHERE id = NEW.transaction_type_id AND user_id = NEW.user_id) THEN
    RAISE EXCEPTION 'Category and transaction type must belong to the same workspace.';
  END IF;
  RETURN NEW;
END;
$$;
